"""Convert the Lucide SVG icons (orbit/ui/icons) to Android vector drawables.

    python tools/svg_to_vector.py
Writes android/app/src/main/res/drawable/ic_<name>.xml (white strokes; tinted in Compose).
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "orbit" / "ui" / "icons"
OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable"


def num(v, default=0.0):
    return float(v) if v not in (None, "") else default


def element_path(el) -> str | None:
    tag = el.tag.split("}")[-1]
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a.get("cx")), num(a.get("cy")), num(a.get("r"))
        return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0"
    if tag == "ellipse":
        cx, cy, rx, ry = num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry"))
        return f"M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0a{rx},{ry} 0 1,0 {-2 * rx},0"
    if tag == "line":
        return f"M{num(a.get('x1'))},{num(a.get('y1'))}L{num(a.get('x2'))},{num(a.get('y2'))}"
    if tag in ("polyline", "polygon"):
        pts = re.findall(r"-?[\d.]+", a["points"])
        pairs = [f"{pts[i]},{pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height"))
        rx = num(a.get("rx"), num(a.get("ry")))
        if not rx:
            return f"M{x},{y}h{w}v{h}h{-w}Z"
        rx = min(rx, w / 2, h / 2)
        return (f"M{x + rx},{y}h{w - 2 * rx}a{rx},{rx} 0 0,1 {rx},{rx}v{h - 2 * rx}"
                f"a{rx},{rx} 0 0,1 {-rx},{rx}h{-(w - 2 * rx)}a{rx},{rx} 0 0,1 {-rx},{-rx}"
                f"v{-(h - 2 * rx)}a{rx},{rx} 0 0,1 {rx},{-rx}Z")
    return None


def convert(svg: Path) -> str:
    root = ET.fromstring(re.sub(r"<!--.*?-->", "", svg.read_text(encoding="utf-8"), flags=re.S))
    paths = [p for el in root.iter() if (p := element_path(el))]
    body = "\n".join(
        f'    <path android:pathData="{p}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>'
        for p in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Lucide icon (ISC license), generated by tools/svg_to_vector.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
            f"{body}\n</vector>\n")


OUT.mkdir(parents=True, exist_ok=True)
for svg in sorted(SRC.glob("*.svg")):
    (OUT / f"ic_{svg.stem}.xml").write_text(convert(svg), encoding="utf-8")
    print("ic_" + svg.stem)
